from PIL import Image
import os

def shift_and_slice_mirror(image_path, output_dir, shift_steps=10, shift_step_pixels=5):
    """
    Shift a mirrored copy layer over the original, save slices at each step.
    
    Args:
        image_path (str): Path to the input image.
        output_dir (str): Directory to save sliced images.
        shift_steps (int): Number of shift iterations.
        shift_step_pixels (int): Pixels to shift the mirrored layer each time.
    """
    # Load original image
    original = Image.open(image_path)
    width, height = original.size
    
    # Create output directory if it doesn't exist
    os.makedirs(output_dir, exist_ok=True)
    
    for step in range(shift_steps):
        # Create a new image with the original as base
        shifted = original.copy()
        
        # Create mirrored version (flip horizontally)
        mirrored = original.transpose(Image.FLIP_LEFT_RIGHT)
        
        # Shift the mirrored layer (e.g., move right by `shift_step_pixels * step`)
        shift_x = shift_step_pixels * step
        shifted.paste(mirrored, (shift_x, 0), mirrored)  # Overlay mirrored layer
        
        # Save the shifted composite
        output_path = os.path.join(output_dir, f"shifted_{step}.png")
        shifted.save(output_path)
        print(f"Saved: {output_path}")

# Example usage
